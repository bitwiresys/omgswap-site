  function fmtDate(iso) {
    var months = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];
    var d = new Date(iso + 'T00:00:00');
    return d.getDate() + ' ' + months[d.getMonth()] + ' ' + d.getFullYear();
  }

